// assets/js/project-admin.js

(function () {
  // Elements
  const authSection = document.getElementById('auth-section');
  const formSection = document.getElementById('form-section');
  const authBtn = document.getElementById('auth-btn');
  const authTokenInput = document.getElementById('admin-token');
  const authStatus = document.getElementById('auth-status');
  const projectForm = document.getElementById('project-form');
  const submitBtn = document.getElementById('submit-btn');
  const submitText = document.getElementById('submit-text');
  const submitSpinner = document.getElementById('submit-spinner');
  const formStatus = document.getElementById('form-status');
  const resetBtn = document.getElementById('reset-btn');

  // Auto-generate slug from title
  const titleInput = document.getElementById('project-title');
  const slugInput = document.getElementById('project-slug');

  titleInput?.addEventListener('input', () => {
    if (!slugInput.value || slugInput.dataset.autoGenerated === 'true') {
      const slug = titleInput.value
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-+|-+$/g, '');
      slugInput.value = slug;
      slugInput.dataset.autoGenerated = 'true';
    }
  });

  slugInput?.addEventListener('input', () => {
    slugInput.dataset.autoGenerated = 'false';
  });

  // Authentication
  let adminToken = sessionStorage.getItem('admin_token');

  if (adminToken) {
    showFormSection();
  }

  authBtn?.addEventListener('click', () => {
    const token = authTokenInput.value.trim();
    if (!token) {
      showStatus(authStatus, 'Please enter your admin token', 'error');
      return;
    }

    // Store token in session
    adminToken = token;
    sessionStorage.setItem('admin_token', token);
    showStatus(authStatus, 'Authenticated successfully', 'success');
    setTimeout(showFormSection, 500);
  });

  function showFormSection() {
    authSection.style.display = 'none';
    formSection.style.display = 'block';
  }

  // Form submission
  projectForm?.addEventListener('submit', async (e) => {
    e.preventDefault();

    if (!adminToken) {
      showStatus(formStatus, 'Not authenticated. Please refresh and authenticate first.', 'error');
      return;
    }

    // Gather form data
    const title = document.getElementById('project-title').value.trim();
    const slug = document.getElementById('project-slug').value.trim();
    const status = document.getElementById('project-status').value;
    const health = document.getElementById('project-health').value;
    const description = document.getElementById('project-description').value.trim();
    const techStackRaw = document.getElementById('project-tech-stack').value;
    const uptime = document.getElementById('project-uptime').value;
    const lastUpdated = document.getElementById('project-last-updated').value;
    const image = document.getElementById('project-image').value.trim();
    const content = document.getElementById('project-content').value.trim();

    // Validate required fields
    if (!title || !slug || !status || !description) {
      showStatus(formStatus, 'Please fill in all required fields', 'error');
      return;
    }

    // Parse tech stack
    const techStack = techStackRaw
      ? techStackRaw.split(',').map(t => t.trim()).filter(Boolean)
      : [];

    // Build frontmatter
    const frontmatter = {
      layout: 'default',
      title,
      status,
      ...(health && { health }),
      ...(techStack.length > 0 && { tech_stack: techStack }),
      ...(uptime && { uptime_pct: parseFloat(uptime) }),
      ...(lastUpdated && { last_updated: lastUpdated }),
      ...(image && { image }),
    };

    // Build full markdown file
    const yamlLines = ['---'];
    for (const [key, value] of Object.entries(frontmatter)) {
      if (Array.isArray(value)) {
        yamlLines.push(`${key}:`);
        value.forEach(item => yamlLines.push(`  - ${item}`));
      } else {
        yamlLines.push(`${key}: ${JSON.stringify(value)}`);
      }
    }
    yamlLines.push('---');
    yamlLines.push('');
    yamlLines.push(content || `# ${title}\n\n${description}`);

    const markdownContent = yamlLines.join('\n');

    // Get API URL from Jekyll config (injected via script tag or use default)
    const apiUrl = window.projectAdminApiUrl || '/api/create-project';

    // Show loading state
    submitBtn.disabled = true;
    submitText.style.display = 'none';
    submitSpinner.style.display = 'inline';
    showStatus(formStatus, '', '');

    try {
      const response = await fetch(apiUrl, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${adminToken}`,
        },
        body: JSON.stringify({
          slug,
          content: markdownContent,
        }),
      });

      const result = await response.json();

      if (!response.ok) {
        throw new Error(result.error || `HTTP ${response.status}`);
      }

      showStatus(formStatus, `✓ Project "${title}" created successfully! It will appear after the next build.`, 'success');
      projectForm.reset();
      slugInput.dataset.autoGenerated = 'true';

      // Scroll to status
      formStatus.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
    } catch (error) {
      console.error('Project creation error:', error);
      showStatus(formStatus, `✗ Failed to create project: ${error.message}`, 'error');
    } finally {
      submitBtn.disabled = false;
      submitText.style.display = 'inline';
      submitSpinner.style.display = 'none';
    }
  });

  // Reset button
  resetBtn?.addEventListener('click', () => {
    if (confirm('Reset all form fields?')) {
      projectForm.reset();
      slugInput.dataset.autoGenerated = 'true';
      showStatus(formStatus, '', '');
    }
  });

  // Helper to show status messages
  function showStatus(element, message, type) {
    if (!element) return;
    element.textContent = message;
    element.className = 'admin-status';
    if (type) {
      element.classList.add(`admin-status-${type}`);
    }
  }
})();
